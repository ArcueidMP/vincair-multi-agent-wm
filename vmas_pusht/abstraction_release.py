"""Matched support ablations after real bounded-action histories.

Every branch starts at the same complete intermediate state. Turning off an
actuator leaves a collidable body; disabling collisions is an analytical contact
intervention, not an executable robot policy. Retreat/return is a finite-force
physical primitive sequence. These continuation states are not exact coarse
aliases across histories, and are outside reset-only response-model training.
"""
import argparse
import hashlib
import importlib.metadata
import itertools
import json
import math
from pathlib import Path
import subprocess

import torch

from vmas_pusht.boundary import _at_wall, _finite, _rotate, surface_gaps
from vmas_pusht.physical_abstraction import (
    HELPER_LOCAL, helper_action, model_features, norm_bound, physical_state, setup_scene,
)
from vmas_pusht.scenario import make, wrap
from vmas_pusht.snapshot import capture, restore

BRANCHES = ("keep", "zero_force", "contact_disabled", "retreat_return")


def primary_program(angles, directions, strengths):
    angle = angles + torch.deg2rad(directions)
    return torch.stack((angle.sin(), -angle.cos()), 1) * strengths[:, None]


def retreat_or_return(env, anchor, angles, step, kp=30., kd=4.):
    """Ten-step retreat then moving contact reacquisition; no position reset."""
    helper, bar = env.world.agents[1], env.scenario.bar
    if step < 10:
        target = anchor + _rotate(torch.tensor([.15, -.15]).expand(env.num_envs, 2), angles)
        target_velocity = torch.zeros_like(target)
    else:
        offset = _rotate(torch.tensor(HELPER_LOCAL).expand(env.num_envs, 2), bar.state.rot[:, 0])
        target = bar.state.pos + offset
        target_velocity = bar.state.vel + bar.state.ang_vel * torch.stack((-offset[:, 1], offset[:, 0]), 1)
    return norm_bound(kp * (target - helper.state.pos) + kd * (target_velocity - helper.state.vel))


def pose_response(env, start):
    return torch.cat((env.scenario.bar.state.pos - start[:, :2],
                      wrap(env.scenario.bar.state.rot - start[:, 2:3])), 1)


def basic_summary(y, baseline, any_contact, double_contact, norm_impulse, effort, travel,
                  finite, wall, initial_contact, release_clear, returned):
    delta = y - baseline
    def group(mask):
        return {"cases": int(mask.sum()),
                "translation_difference_rms_units": float(delta[mask, :2].square().sum(1).mean().sqrt()),
                "angle_difference_rms_rad": float(delta[mask, 2].square().mean().sqrt())} if mask.any() else {"cases": 0}
    return {
        "mean_abs_rotation_rad": float(y[:, 2].abs().mean()),
        "mean_translation_units": float(y[:, :2].norm(dim=1).mean()),
        "helper_any_contact_fraction": float(any_contact.mean()),
        "helper_double_contact_fraction": float(double_contact.mean()),
        "norm_impulse_mean_by_agent": norm_impulse.mean(0).tolist(),
        "squared_force_effort_mean_by_agent": effort.mean(0).tolist(),
        "travel_mean_by_agent_units": travel.mean(0).tolist(),
        "finite_all": bool(finite.all()), "wall_cases": int(wall.sum()),
        "difference_vs_keep": group(torch.ones(len(y), dtype=torch.bool)),
        "difference_vs_keep_initially_touching": group(initial_contact),
        "retreated_clear_by_step10_fraction": float(release_clear.float().mean()),
        "contact_returned_after_retreat_fraction": float(returned.float().mean()),
    }


@torch.no_grad()
def audit_group(friction=1.5, substeps=10, support="world_anchor", horizon=30, checkpoint=None):
    # The warmup time and action histories are fixed before inspecting outcomes.
    histories = ((1, .3, -20.), (5, .6, 0.), (10, .9, 20.))
    programs = (("constant", -35., .45), ("constant", 0., .6), ("constant", 35., .75),
                ("switch", -20., .6), ("switch", 20., .6))
    rows = [dict(angle_deg=angle, error=error, warm_steps=h[0], warm_strength=h[1],
                 warm_direction=h[2], program=p[0], direction=p[1], strength=p[2])
            for angle, error, h, p in itertools.product((0., 30.), ((0., 0.), (.004, -.004)), histories, programs)]
    n = len(rows)
    config = dict(num_envs=n, friction_ratio=friction, substeps=substeps, device="cpu", seed=42)
    source = make(**config)
    angles = torch.tensor([math.radians(r["angle_deg"]) for r in rows])
    anchor = setup_scene(source, angle=angles, helper_error=[r["error"] for r in rows])
    warm_steps = torch.tensor([r["warm_steps"] for r in rows])
    warm_u = primary_program(angles, torch.tensor([r["warm_direction"] for r in rows]),
                             torch.tensor([r["warm_strength"] for r in rows]))
    warm_trajectories = [physical_state(source).clone()]
    intermediate = []
    # Capture each history at its declared length, then assemble the rows. This
    # keeps histories genuinely generated by legal forces, with no projection.
    for step in range(1, int(warm_steps.max()) + 1):
        source.step([warm_u, helper_action(source, support, anchor, reference_angle=angles)])
        warm_trajectories.append(physical_state(source).clone())
        if step in warm_steps.tolist():
            intermediate.append((step, capture(source)))
    # Snapshot row assembly preserves every physical and bookkeeping field.
    # All snapshots have identical configuration and batch size.
    from dataclasses import replace
    saved = intermediate[0][1]
    def merge(values):
        if values[0] is None:
            return None
        result = values[0].clone()
        for (step, _), value in zip(intermediate, values):
            result[warm_steps == step] = value[warm_steps == step]
        return result
    entities = []
    for k, entity in enumerate(saved.entities):
        state_fields = {field: merge([s.entities[k].state[field] for _, s in intermediate]) for field in entity.state}
        action = None if entity.action is None else {
            field: merge([s.entities[k].action[field] for _, s in intermediate]) for field in entity.action}
        entities.append(replace(entity, state=state_fields, action=action))
    saved = replace(saved, entities=tuple(entities),
                    scenario={field: merge([s.scenario[field] for _, s in intermediate]) for field in saved.scenario},
                    steps=merge([s.steps for _, s in intermediate]))
    restore(source, saved)
    start = source.scenario.t_pose().clone()
    initial_state = physical_state(source).clone()
    gaps = surface_gaps(source)[:, 1]
    initially_touching = gaps.amin(1) <= .005
    initial_double = (gaps <= .005).all(1)
    direction = torch.tensor([r["direction"] for r in rows])
    strength = torch.tensor([r["strength"] for r in rows])
    first_u = primary_program(angles, direction, strength)
    control_reference = anchor
    if support == "preloaded_anchor":
        control_reference = anchor + _rotate(torch.tensor([-.01, .01]).expand(n, 2), angles)
    coarse, full = model_features(source, first_u, horizon, control_reference)
    prediction = None
    if checkpoint is not None:
        from vmas_pusht.abstraction_models import predict_checkpoint
        prediction = predict_checkpoint(checkpoint, coarse).detach().cpu()
    outcomes, raw = {}, {}
    for branch in BRANCHES:
        env = make(**config)
        restore(env, saved)
        torch.testing.assert_close(physical_state(env), initial_state, rtol=0, atol=0)
        if branch == "contact_disabled":
            # Structural do(contact=off), after exact state restoration. This
            # creates a ghost helper and is only a causal-mechanism diagnostic.
            env.world.agents[1]._collide = False
        trajectory = [physical_state(env).clone()]
        commands = []
        any_contact, double_contact = torch.zeros(n), torch.zeros(n)
        norm_impulse, effort, travel = [torch.zeros(n, 2) for _ in range(3)]
        finite, wall = _finite(env), _at_wall(env)
        clear, returned = torch.zeros(n, dtype=torch.bool), torch.zeros(n, dtype=torch.bool)
        max_norm = 0.
        for step in range(horizon):
            dirs = direction.clone()
            if step >= 10:
                switching = torch.tensor([r["program"] == "switch" for r in rows])
                dirs[switching] *= -1
            primary = primary_program(angles, dirs, strength)
            if branch == "zero_force":
                helper = torch.zeros(n, 2)
            elif branch == "retreat_return":
                helper = retreat_or_return(env, anchor, angles, step)
            else:
                helper = helper_action(env, support, anchor, reference_angle=angles)
            action = torch.stack((primary, helper), 1)
            old_pos = torch.stack([a.state.pos.clone() for a in env.world.agents], 1)
            env.step([action[:, 0], action[:, 1]])
            norm = action.norm(dim=-1)
            max_norm = max(max_norm, float(norm.max()))
            norm_impulse += norm * env.world.dt * env.scenario.agent_force
            effort += norm.square() * env.world.dt
            travel += (torch.stack([a.state.pos for a in env.world.agents], 1) - old_pos).norm(dim=-1)
            geometric = surface_gaps(env)[:, 1]
            contacting = geometric.amin(1) <= .005
            double = (geometric <= .005).all(1)
            if branch == "contact_disabled":
                contacting.zero_(); double.zero_()
            any_contact += contacting
            double_contact += double
            if step == 9:
                clear = geometric.amin(1) > .01
            if step >= 10:
                returned |= clear & contacting
            finite &= _finite(env); wall |= _at_wall(env)
            trajectory.append(physical_state(env).clone()); commands.append(action.clone())
        if max_norm > 1 + 1e-6 or not finite.all():
            raise AssertionError("Invalid bounded-force rollout")
        y = pose_response(env, start)
        raw[branch] = dict(Y=y, trajectory=torch.stack(trajectory, 1), actions=torch.stack(commands, 1),
                           norm_impulse=norm_impulse, effort=effort, travel=travel)
        outcomes[branch] = basic_summary(y, raw["keep"]["Y"], any_contact / horizon, double_contact / horizon,
                                        norm_impulse, effort, travel, finite, wall, initially_touching, clear, returned)
        outcomes[branch]["maximum_action_norm"] = max_norm
        if prediction is not None:
            valid = torch.tensor([r["program"] == "constant" for r in rows])
            error = prediction[valid] - y[valid]
            outcomes[branch]["frozen_continuation_model_error"] = {
                "cases": int(valid.sum()), "translation_rmse_units": float(error[:, :2].square().sum(1).mean().sqrt()),
                "angle_rmse_rad": float(error[:, 2].square().mean().sqrt()),
                "caution": "Continuation states are OOD for reset-only training; off-contact branches change the model regime."}
    summary = {"friction_ratio": friction, "substeps": substeps, "support": support, "horizon": horizon,
               "cases": n, "initial_helper_contact_fraction": float(initially_touching.float().mean()),
               "initial_double_contact_fraction": float(initial_double.float().mean()), "branches": outcomes}
    return summary, dict(rows=rows, initial_state=initial_state, X_coarse=coarse, X_full=full, anchor=anchor,
                         control_reference=control_reference, reference_angle=angles,
                         warmup_trajectory=torch.stack(warm_trajectories, 1), prediction=prediction, branches=raw)


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--out", type=Path, default=Path("data/novelty/abstraction_release.json"))
    p.add_argument("--models", type=Path, default=Path("data/novelty/abstraction_models.pt"))
    p.add_argument("--preloaded-models", type=Path, default=Path("data/novelty/abstraction_models_preload.pt"))
    p.add_argument("--frictions", nargs="+", type=float, default=[.75, 1.5, 2.25])
    p.add_argument("--substeps", nargs="+", type=int, default=[5, 10, 20])
    p.add_argument("--supports", nargs="+", choices=["world_anchor", "preloaded_anchor"],
                   default=["world_anchor", "preloaded_anchor"])
    p.add_argument("--horizon", type=int, default=30)
    args = p.parse_args()
    if args.horizon < 20:
        p.error("horizon must allow ten retreat steps and at least ten return steps")
    torch.set_num_threads(1)
    checkpoints, model_hashes = {}, {}
    for support, path in (("world_anchor", args.models), ("preloaded_anchor", args.preloaded_models)):
        if path.exists():
            artifact = torch.load(path, map_location="cpu")
            checkpoints[support] = artifact["checkpoints"]["world_anchor/coarse_body_small/seed0"]
            model_hashes[support] = hashlib.sha256(path.read_bytes()).hexdigest()
    summaries, raw = [], []
    for support, friction, substeps in itertools.product(args.supports, args.frictions, args.substeps):
        summary, records = audit_group(friction, substeps, support, args.horizon, checkpoints.get(support))
        summaries.append(summary); raw.append(records)
        print(json.dumps({k: v for k, v in summary.items() if k != "branches"}), flush=True)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    raw_path = args.out.with_suffix(".pt")
    torch.save({"groups": raw}, raw_path)
    paths = [Path(__file__), *(Path(__file__).with_name(n) for n in
             ("physical_abstraction.py", "scenario.py", "snapshot.py", "abstraction_models.py"))]
    report = {"schema_version": 1, "arguments": {k: str(v) if isinstance(v, Path) else v for k, v in vars(args).items()},
              "git_commit": subprocess.check_output(["git", "rev-parse", "HEAD"], text=True).strip(),
              "versions": {n: importlib.metadata.version(n) for n in ("torch", "vmas", "numpy")},
              "source_sha256": {str(path): hashlib.sha256(path.read_bytes()).hexdigest() for path in paths},
              "model_sha256": model_hashes, "raw_file": str(raw_path),
              "raw_sha256": hashlib.sha256(raw_path.read_bytes()).hexdigest(), "groups": summaries,
              "limitations": ["Counterfactual branches share full intermediate states; different histories are not exact coarse aliases.",
                  "Contact-disabled is an analytical intervention, not an executable robot policy.",
                  "Retreat-return only tests a local primitive sequence, not a new full manipulation task.",
                  "No model or helper was retrained on continuation states or used to select these programs."]}
    args.out.write_text(json.dumps(report, indent=2, allow_nan=False) + "\n")
    print("->", args.out)


if __name__ == "__main__":
    main()
